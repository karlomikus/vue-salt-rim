import fs from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";
import ts from "typescript";

const STRING = ts.factory.createKeywordTypeNode(ts.SyntaxKind.StringKeyword); // `string`
const BLOB = ts.factory.createTypeReferenceNode(ts.factory.createIdentifier("Blob")); // `Blob`
const NULL = ts.factory.createLiteralTypeNode(ts.factory.createNull()); // `null`

function isNullable(schemaObject: { nullable?: boolean; type?: unknown }): boolean {
    if (schemaObject.nullable === true) {
        return true;
    }
    return Array.isArray(schemaObject.type) && schemaObject.type.includes("null");
}

const ast = await openapiTS(new URL("../spec.yml", import.meta.url), {
    cwd: new URL("..", import.meta.url),
    transform(schemaObject) {
        if (schemaObject.format === "binary") {
            const types: ts.TypeNode[] = [STRING, BLOB];
            if (isNullable(schemaObject)) {
                types.push(NULL);
            }
            return ts.factory.createUnionTypeNode(types);
        }
    },
});

const contents = astToString(ast);
fs.writeFileSync(
    new URL("../src/api/api.d.ts", import.meta.url),
    `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

${contents}`,
);
